create table if not exists public.r24_user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('technician','customer')),
  created_at timestamptz not null default now()
);

create table if not exists public.r24_installations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  location text,
  timezone text not null default 'America/Argentina/Cordoba',
  status text not null default 'active' check (status in ('active','paused','maintenance')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.r24_installation_members (
  id uuid primary key default gen_random_uuid(),
  installation_id uuid not null references public.r24_installations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'owner' check (role in ('owner','operator','viewer')),
  created_at timestamptz not null default now(),
  unique (installation_id, user_id)
);

create table if not exists public.r24_devices (
  id uuid primary key default gen_random_uuid(),
  installation_id uuid not null references public.r24_installations(id) on delete cascade,
  provider text not null default 'tuya' check (provider in ('tuya')),
  external_device_id text not null,
  label text not null,
  region text not null default 'us',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, external_device_id)
);

create table if not exists public.r24_zones (
  id uuid primary key default gen_random_uuid(),
  installation_id uuid not null references public.r24_installations(id) on delete cascade,
  device_id uuid not null references public.r24_devices(id) on delete cascade,
  channel_code text not null,
  name text not null,
  sort_order integer not null default 0,
  image_url text,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  unique (device_id, channel_code)
);

create table if not exists public.r24_settings (
  installation_id uuid primary key references public.r24_installations(id) on delete cascade,
  settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.r24_programs (
  id uuid primary key default gen_random_uuid(),
  installation_id uuid not null references public.r24_installations(id) on delete cascade,
  program jsonb not null default '{}'::jsonb,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.r24_events (
  id bigint generated by default as identity primary key,
  installation_id uuid not null references public.r24_installations(id) on delete cascade,
  created_at timestamptz not null default now(),
  event text not null,
  detail text not null default '',
  zone_id uuid references public.r24_zones(id) on delete set null,
  ok boolean not null default true,
  source text not null default 'server'
);

create table if not exists public.r24_runtime (
  installation_id uuid primary key references public.r24_installations(id) on delete cascade,
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists r24_members_user_idx on public.r24_installation_members(user_id);
create index if not exists r24_devices_installation_idx on public.r24_devices(installation_id);
create index if not exists r24_zones_installation_idx on public.r24_zones(installation_id);
create index if not exists r24_programs_installation_idx on public.r24_programs(installation_id);
create index if not exists r24_events_installation_created_idx on public.r24_events(installation_id, created_at desc);

create or replace function public.r24_is_technician()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select exists (
    select 1 from public.r24_user_roles r
    where r.user_id = (select auth.uid()) and r.role = 'technician'
  );
$$;

