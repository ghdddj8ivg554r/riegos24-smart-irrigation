create policy "r24_roles_read_self" on public.r24_user_roles
for select to authenticated using (user_id = (select auth.uid()));

create policy "r24_members_read_self_or_technician" on public.r24_installation_members
for select to authenticated
using (user_id = (select auth.uid()) or public.r24_is_technician());

create policy "r24_installations_read_member_or_technician" on public.r24_installations
for select to authenticated
using (
  public.r24_is_technician()
  or exists (
    select 1 from public.r24_installation_members m
    where m.installation_id = public.r24_installations.id
      and m.user_id = (select auth.uid())
  )
);

